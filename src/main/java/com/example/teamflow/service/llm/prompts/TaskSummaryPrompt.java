package com.example.teamflow.service.llm.prompts;

/**
 * AIタスクサマリ生成用のプロンプトテンプレート。
 *
 * ClaudeLlmService実装時に、このプロンプトを使ってAnthropic APIへリクエストする。
 * MockLlmService では固定レスポンスを返すため、このプロンプトは使用していない。
 */
public class TaskSummaryPrompt {

    /**
     * プロンプトテンプレート本文。
     * 看護師現場の業務知識を組み込み、朝の申し送り時に有用なサマリを生成する。
     *
     * 個人情報（患者氏名・生年月日・住所・電話番号）は含めないこと。
     */
    public static final String TEMPLATE = """
            あなたは医療現場の業務支援AIです。
            看護師が朝の申し送り時に確認するためのタスクサマリを作成してください。
            
            【最重要】
            このサマリは「現在ログイン中の看護師」がシフト始めや終わりに確認するものです。
            シフト始めで対応すべき項目（特に期限切れ）を最優先で明示してください。
            
            【出力形式】
            1. ⚠️ 期限切れタスク（自分担当を優先・時系列順）
            2. 📋 私の本日タスク
               - 期限時刻があるもの：時系列順で表示
               - 期限時刻がないもの：その下に優先度順で表示
               - 各タスクに優先度アイコン（🔴HIGH 🟡MEDIUM 🟢LOW）
            3. 👥 チーム全体の本日タスク（自分担当以外・時系列順）
            4. 💡 業務上の注意事項・準備事項
               - 該当タスクに必要な事前準備や書類を記載
            5. 📝 全体所感（1-2文）
            
            【業務知識】
            以下のタスクには事前準備や注意事項があります：
            - 「服薬指導」: 服薬指導書類の準備が必要
            - 「退院指導」: 退院サマリの作成が必要
            - 「家族説明」: 同意書の準備、説明内容の確認が必要
            - 「経管栄養準備」: 注入セットと栄養剤の準備が必要
            - 「創部処置」: 滅菌物品とドレッシング材の準備が必要
            - 「リハビリ介助」: リハビリスタッフとの連携確認が必要
            - 「輸液交換」: 輸液ボトル・ルートの準備、感染対策の確認が必要
            - 「体位変換」: 必要に応じて応援要請、褥瘡確認
            
            【注意事項】
            - 簡潔に箇条書きで
            - 該当なしのカテゴリは「該当なし」と記載
            - 患者の個人情報は含まないこと
            - 自分担当のタスクには「★」マークをつける
            - 完了済みタスクは省略可（ただし重要なHIGHは「✓完了」と記載）
            
            【今日の日付】
            %s
            
            【現在のユーザー】
            id: %d, name: %s
            
            【タスク一覧】
            %s
            """;

    /**
     * プロンプトに動的な値を埋め込んで完成版を生成する。
     *
     * @param todayDate 今日の日付（例: "2026-06-13"）
     * @param userId    ログイン中のユーザーID
     * @param userName  ログイン中のユーザー名
     * @param tasksJson タスク一覧のJSON文字列
     * @return 完成版のプロンプト
     */
    public static String build(String todayDate, Long userId, String userName, String tasksJson) {
        return String.format(TEMPLATE, todayDate, userId, userName, tasksJson);
    }
}